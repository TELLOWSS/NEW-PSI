import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try {
  const page=await browser.newPage({viewport:{width:390,height:844}});
  await page.goto(process.env.PSI_NEXUS_FIXTURE_URL || 'http://127.0.0.1:4188/tests/fixtures/nexus-priority.html');
  const priority=page.getByRole('region',{name:'우선 확인할 후속조치'});
  await priority.getByRole('button',{name:'기한 초과 1건'}).click();
  assert.equal(await priority.getByRole('heading',{name:'기한 초과 조치 1건'}).count(),1);
  assert.equal(await priority.getByRole('button',{name:'관련 기록 열기'}).count(),1);
  await priority.getByRole('button',{name:'관련 기록 열기'}).click();
  assert.match(await priority.getByRole('alert').textContent(),/동일 식별자/);
  assert.notEqual(await page.title(),'synthetic-one');
  await page.getByRole('button',{name:'합성 중복 제거'}).click();
  await page.getByRole('button',{name:'전체 화면 몰입 보기 ⤢'}).click();
  await priority.getByRole('button',{name:'관련 기록 열기'}).click();
  await page.waitForFunction(()=>document.title==='synthetic-one');
  assert.equal(await page.locator('.safety-nexus.is-immersive').count(),0);
  assert.equal(await page.locator('#root').evaluate(root=>root.inert),false);
  assert.equal(await page.title(),'synthetic-one');
  await priority.getByRole('button',{name:'미완료 2건'}).click();
  assert.equal(await priority.getByRole('heading',{name:'미완료 조치 2건'}).count(),1);
  assert.equal(await priority.getByRole('button',{name:'관련 기록 열기'}).count(),2);
  await page.getByRole('button',{name:'완료로 기록된 조치 1건',exact:true}).click();
  assert.equal(await priority.getByRole('heading',{name:'완료로 기록된 조치 1건'}).count(),1);
  await page.getByRole('button',{name:'Q2 관련 기록 보기'}).click();
  assert.equal(await page.getByText('해당 문항 조치 이력 보기',{exact:true}).count(),3);
  await priority.getByRole('button',{name:'재확인 기한초과 1건'}).click();
  assert.equal(await priority.getByRole('heading',{name:'재확인 기한초과 1건'}).count(),1);
  assert.equal(await priority.getByRole('button',{name:'관련 기록 열기'}).count(),1);
  await priority.getByRole('button',{name:'관련 기록 열기'}).click();
  assert.equal(await page.title(),'synthetic-one');
  await priority.getByRole('button',{name:'미완료 2건'}).click();
  await page.getByRole('combobox',{name:'공종 선택'}).selectOption('다른 공종');
  assert.equal(await priority.getByRole('heading',{name:'미완료 조치 0건'}).count(),1);
  await page.getByRole('combobox',{name:'공종 선택'}).selectOption('가상 공종');
  await page.getByRole('combobox',{name:'작성 월 선택'}).selectOption('2020-01');
  await page.getByRole('button',{name:'합성 기록 제거'}).click();
  assert.equal(await page.getByRole('combobox',{name:'공종 선택'}).inputValue(),'가상 공종');
  assert.equal(await page.getByRole('combobox',{name:'작성 월 선택'}).inputValue(),'2020-01');
  assert.match(await page.getByRole('combobox',{name:'공종 선택'}).locator('option:checked').textContent(),/현재 기록 없음/);
  console.log('PASS: 중복 이력 제거, 상태별 목록·건수, 기록 연결 및 필터');
} finally { await browser.close(); }
