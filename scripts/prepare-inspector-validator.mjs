import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
export async function generateInspectorValidator(){
 const source=await readFile(new URL('../lib/inspector/visionSchema.ts',import.meta.url),'utf8');
 const js=ts.transpile(source,{module:ts.ModuleKind.ESNext});
 const {visionSchema}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
 const ajv=new Ajv2020({allErrors:false,strict:true,code:{source:true,esm:true,lines:true}});
 const code=standalone(ajv,ajv.compile(visionSchema)).replace(/const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,'import $1 from "ajv/dist/runtime/ucs2length.js";');
 if(code.includes('require('))throw new Error('Unexpected standalone validator runtime dependency');
 return '// Generated by scripts/prepare-inspector-validator.mjs. Do not edit.\n'+code;
}
if(process.argv[1]===fileURLToPath(import.meta.url))await writeFile(new URL('../lib/inspector/visionValidator.generated.js',import.meta.url),await generateInspectorValidator());
